#!/usr/bin/env python3
"""Generate look/world_surface.gdshaderinc from the shared WorldSurface.ush (Textures thread, ONE source for lab, Unreal, Godot).
Godot's shading language has no mutable globals, so every GLOBAL becomes a field of struct WsG and every library function takes
`inout WsG Wg_` first (calls pass Wg_ on). Everything else is the source as it stands. Never edit the output: edit WorldSurface.ush
and run this again (as ws_export.py did for Unreal).
Usage: python3 -I tools/ws_to_godot.py <WorldSurface.ush> <out.gdshaderinc>"""
import re, sys, hashlib

HEAD = r"""// GENERATED by tools/ws_to_godot.py from WorldSurface.ush (md5 %s). Do not edit: edit the source and regenerate.
// Godot head (mirrors WorldSurface_hlsl.h without WS_LAB: textures as stored, v runs down the picture).
#define float2 vec2
#define float3 vec3
#define float4 vec4
#define int3 ivec3
#define uint3 uvec3
#define lerp mix
#define frac fract
#define ddx dFdx
#define ddy dFdy
#define atan2(y, x) atan(y, x)
#define saturate(x) clamp(x, 0., 1.)
#define TEXARG(t) sampler2D t
#define TEXUSE(t) t
#define TEXW(t, uv, dx, dy) textureGrad(t, uv, dx, dy)
#define TEXC(t, uv) texture(t, uv)
#define WS_COUNT_HASH
#define WS_COUNT_READ
#define WS_COUNT_READ4
#define WS_MAPUV(p) clamp(vec2(((p).x + 300.)/600., 1. - ((p).y + 300.)/600.), 0., 1.)
vec3 WsUnpackBC5(vec4 c){ vec2 xy = c.rg*2. - 1.; return vec3(xy, sqrt(clamp(1. - dot(xy, xy), 0., 1.))); }
#define WS_UNPACKN(c) WsUnpackBC5(c)
"""

def main(src, dst):
    text = open(src).read()
    md5 = hashlib.md5(text.encode()).hexdigest()
    globs = []          # (type, name, init)
    out_lines = []
    for line in text.split("\n"):
        m = re.match(r"\s*GLOBAL\s+(\w+)\s+(\w+)\s*(?:=\s*([^;]+))?;(.*)$", line)
        if m:
            globs.append((m.group(1), m.group(2), (m.group(3) or "").strip()))
            continue
        out_lines.append(line)
    body = "\n".join(out_lines)
    # top-level function definitions: a type at column 0, a name, "("
    fdef = re.compile(r"^(\w+)[ \t]+(\w+)[ \t]*\(", re.M)
    names = sorted({m.group(2) for m in fdef.finditer(body) if m.group(1) not in ("struct", "return", "else", "if", "for", "while")})
    # 1. definitions take W first
    def add_param(m):
        return "%s %s(inout WsG Wg_, " % (m.group(1), m.group(2))
    body = fdef.sub(lambda m: add_param(m) if m.group(2) in names else m.group(0), body)
    body = body.replace("(inout WsG Wg_, )", "(inout WsG Wg_)")
    # 2. calls pass W (any use of a library name followed by "(" that is not its definition)
    call = re.compile(r"(?<![\w.])(" + "|".join(map(re.escape, names)) + r")\s*\((?!inout WsG W)")
    body = call.sub(lambda m: m.group(1) + "(Wg_, ", body)
    body = re.sub(r"\(Wg_, \s*\)", "(Wg_)", body)
    # 3. globals are W's fields
    for t, n, _ in globs:
        body = re.sub(r"(?<![\w.])%s(?!\w)" % re.escape(n), "Wg_." + n, body)
    # Godot has no vector-with-scalar bit operators: widen the scalar (the source only uses them on uint3 hashes)
    for a, b in (("h & 65535u", "h & uvec3(65535u)"), ("h >> 16u", "h >> uvec3(16u)"), ("v ^= v >> 16u", "v ^= v >> uvec3(16u)")):
        body = body.replace(a, b)
    struct = "struct WsG {\n" + "".join("  %s %s;\n" % (t, n) for t, n, _ in globs) + "};\n"
    init = "WsG wsNewG() { WsG Wg_;\n" + "".join("  Wg_.%s = %s;\n" % (n, i if i else ("0." if t == "float" else "%s(0.)" % t))
                                            for t, n, i in globs) + "  return Wg_; }\n"
    # the struct must come after other struct definitions it might use and before the first function: put it after the head
    open(dst, "w").write(HEAD % md5 + struct + init + body)
    print("globals %d, functions %d -> %s" % (len(globs), len(names), dst))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
