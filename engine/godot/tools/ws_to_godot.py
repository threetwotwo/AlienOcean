#!/usr/bin/env python3
"""Generate look/world_surface.gdshaderinc from the shared WorldSurface.ush (Textures thread, ONE source for lab, Unreal, Godot).
Godot's shading language has no mutable globals, so every GLOBAL becomes a field of struct WsG and every library function takes
`inout WsG Wg_` first (calls pass Wg_ on). Everything else is the source as it stands. Never edit the output: edit WorldSurface.ush
and run this again (as ws_export.py did for Unreal).
Usage: python3 -I tools/ws_to_godot.py <WorldSurface.ush> <out.gdshaderinc>
       python3 -I tools/ws_to_godot.py --hooks-only <out.gdshaderinc>   (WS_BAKED hooks only, on a generated file)"""
import re, sys, hashlib

HEAD = r"""// GENERATED by tools/ws_to_godot.py from WorldSurface.ush (md5 %s). Do not edit: edit the source and regenerate.
// Godot head (mirrors WorldSurface_hlsl.h without WS_LAB: textures as stored, v runs down the picture).
#define float2 vec2
#define float3 vec3
#define float4 vec4
#define int3 ivec3
#define uint3 uvec3
#define lerp mix
#define frac fract
#define ddx dFdx
#define ddy dFdy
#define atan2(y, x) atan(y, x)
#define saturate(x) clamp(x, 0., 1.)
#define TEXARG(t) sampler2D t
#define TEXUSE(t) t
#define TEXW(t, uv, dx, dy) textureGrad(t, uv, dx, dy)
#define TEXC(t, uv) texture(t, uv)
#define WS_COUNT_HASH
#define WS_COUNT_READ
#define WS_COUNT_READ4
#define WS_MAPUV(p) clamp(vec2(((p).x + 300.)/600., 1. - ((p).y + 300.)/600.), 0., 1.)
vec3 WsUnpackBC5(vec4 c){ vec2 xy = c.rg*2. - 1.; return vec3(xy, sqrt(clamp(1. - dot(xy, xy), 0., 1.))); }
#define WS_UNPACKN(c) WsUnpackBC5(c)
"""

# WS_BAKED (test level thread, 28 Nov 2026): the sand's fixed world-xy noise fields go through hooks, so look/ground_surface.gdshader can read
# them from textures baked once at load (look/sand_bake.gdshader, adapters/godot/sand_bake.gd) instead of hashing them per pixel. Without
# WS_BAKED the hooks are the source's own expressions. Inside the bake box the textures are read; over its last metre they blend back to the
# procedural fields (fields, not results, so no seam); outside, procedural. A shader that defines WS_BAKED declares before the include:
# sampler2D sandA, sandB; vec4 sand_box (org xy, span xy of the texel centres, m); vec2 sand_px; float sand_on.
BAKE_SUBS = (
    ("fbm2n(Wg_, float3(p/1.4, 19.))", "WS_F_RDG(p)"),
    ("fo3(Wg_, float3(p/2.5, 71.))", "WS_F_CW(p)"),
    ("fo3(Wg_, float3(p/2.2, 83.))", "WS_F_WL(p)"),
    ("warp = 1.2*(fbm2n(Wg_, float3(p/0.8, 3.)) - 0.5)*2. + 1.0*(fbm2n(Wg_, float3(p/0.45, 7.)) - 0.5)*2.;",
     "warp = WS_F_WARPC(p) + 1.0*(fbm2n(Wg_, float3(p/0.45, 7.)) - 0.5)*2.;"),
    ("warp += 24.*mB.r - 12. + 10.*fo3(Wg_, float3(p/2.0, 0.));", "warp += 24.*mB.r - 12.;"),
    ("fbm2v(Wg_, float3(p/1.2, 41.))", "WS_F_PR(p)"),
    ("fo3(Wg_, float3(p/2.1, 29.))", "WS_F_DL(p)"),
)
BAKE_BLOCK = r"""// ---------- WS_BAKED hooks (Godot side, tools/ws_to_godot.py): the sand's fixed world-xy noise fields, baked or procedural ----------
float wsWarpC(inout WsG Wg_, float2 p){ return 1.2*(fbm2n(Wg_, float3(p/0.8, 3.)) - 0.5)*2. + 10.*fo3(Wg_, float3(p/2.0, 0.)); }
#ifdef WS_BAKED
float wsBkK(float2 p){ float2 e = min(p - sand_box.xy, sand_box.xy + sand_box.zw - p); return sand_on * clamp(min(e.x, e.y), 0., 1.); }
float4 wsBkRead(inout WsG Wg_, sampler2D t, float2 p){ float2 s = (sand_px - 1.)/sand_box.zw, g = s/sand_px; WS_COUNT_READ
  return textureGrad(t, ((p - sand_box.xy)*s + 0.5)/sand_px, Wg_.gDP.xy*g, Wg_.gDP.zw*g); }
float wsBk1(inout WsG Wg_, float2 p, int c){ float k = wsBkK(p); float b = 0.;
  if (k > 0.) { float4 v = c < 4 ? wsBkRead(Wg_, sandA, p) : wsBkRead(Wg_, sandB, p); b = c == 0 ? v.x : c == 1 ? v.y/7. : c == 2 ? v.z/7. : c == 3 ? v.w/7. : v.x - 8.; }
  if (k >= 1.) return b;
  float f = c == 0 ? fbm2n(Wg_, float3(p/1.4, 19.)) : c == 1 ? fo3(Wg_, float3(p/2.5, 71.)) : c == 2 ? fo3(Wg_, float3(p/2.2, 83.)) : c == 3 ? fo3(Wg_, float3(p/2.1, 29.)) : wsWarpC(Wg_, p);
  return lerp(f, b, k); }
float2 wsBkPr(inout WsG Wg_, float2 p){ float k = wsBkK(p); float2 b = f2(Wg_, 0.); if (k > 0.) b = wsBkRead(Wg_, sandB, p).yz;
  if (k >= 1.) return b; return lerp(fbm2v(Wg_, float3(p/1.2, 41.)), b, k); }
#define WS_F_RDG(p) wsBk1(Wg_, p, 0)
#define WS_F_CW(p) wsBk1(Wg_, p, 1)
#define WS_F_WL(p) wsBk1(Wg_, p, 2)
#define WS_F_DL(p) wsBk1(Wg_, p, 3)
#define WS_F_WARPC(p) wsBk1(Wg_, p, 4)
#define WS_F_PR(p) wsBkPr(Wg_, p)
#else
#define WS_F_RDG(p) fbm2n(Wg_, float3((p)/1.4, 19.))
#define WS_F_CW(p) fo3(Wg_, float3((p)/2.5, 71.))
#define WS_F_WL(p) fo3(Wg_, float3((p)/2.2, 83.))
#define WS_F_DL(p) fo3(Wg_, float3((p)/2.1, 29.))
#define WS_F_WARPC(p) wsWarpC(Wg_, p)
#define WS_F_PR(p) fbm2v(Wg_, float3((p)/1.2, 41.))
#endif
"""

def bake_hooks(body):
    if "WS_BAKED hooks" in body: return body
    for a, b in BAKE_SUBS:
        assert body.count(a) == 1, "bake hook source changed: " + a
        body = body.replace(a, b)
    anchor = "struct WsRipple {"
    assert body.count(anchor) == 1
    return body.replace(anchor, BAKE_BLOCK + anchor)

def main(src, dst):
    text = open(src).read()
    md5 = hashlib.md5(text.encode()).hexdigest()
    globs = []          # (type, name, init)
    out_lines = []
    for line in text.split("\n"):
        m = re.match(r"\s*GLOBAL\s+(\w+)\s+(\w+)\s*(?:=\s*([^;]+))?;(.*)$", line)
        if m:
            globs.append((m.group(1), m.group(2), (m.group(3) or "").strip()))
            continue
        out_lines.append(line)
    body = "\n".join(out_lines)
    # top-level function definitions: a type at column 0, a name, "("
    fdef = re.compile(r"^(\w+)[ \t]+(\w+)[ \t]*\(", re.M)
    names = sorted({m.group(2) for m in fdef.finditer(body) if m.group(1) not in ("struct", "return", "else", "if", "for", "while")})
    # 1. definitions take W first
    def add_param(m):
        return "%s %s(inout WsG Wg_, " % (m.group(1), m.group(2))
    body = fdef.sub(lambda m: add_param(m) if m.group(2) in names else m.group(0), body)
    body = body.replace("(inout WsG Wg_, )", "(inout WsG Wg_)")
    # 2. calls pass W (any use of a library name followed by "(" that is not its definition)
    call = re.compile(r"(?<![\w.])(" + "|".join(map(re.escape, names)) + r")\s*\((?!inout WsG W)")
    body = call.sub(lambda m: m.group(1) + "(Wg_, ", body)
    body = re.sub(r"\(Wg_, \s*\)", "(Wg_)", body)
    # 3. globals are W's fields
    for t, n, _ in globs:
        body = re.sub(r"(?<![\w.])%s(?!\w)" % re.escape(n), "Wg_." + n, body)
    # Godot has no vector-with-scalar bit operators: widen the scalar (the source only uses them on uint3 hashes)
    for a, b in (("h & 65535u", "h & uvec3(65535u)"), ("h >> 16u", "h >> uvec3(16u)"), ("v ^= v >> 16u", "v ^= v >> uvec3(16u)")):
        body = body.replace(a, b)
    struct = "struct WsG {\n" + "".join("  %s %s;\n" % (t, n) for t, n, _ in globs) + "};\n"
    init = "WsG wsNewG() { WsG Wg_;\n" + "".join("  Wg_.%s = %s;\n" % (n, i if i else ("0." if t == "float" else "%s(0.)" % t))
                                            for t, n, i in globs) + "  return Wg_; }\n"
    # the struct must come after other struct definitions it might use and before the first function: put it after the head
    body = bake_hooks(body)
    open(dst, "w").write(HEAD % md5 + struct + init + body)
    print("globals %d, functions %d -> %s" % (len(globs), len(names), dst))

if __name__ == "__main__":
    if sys.argv[1] == "--hooks-only":   # add the WS_BAKED hooks to an already generated file (when the .ush source is not at hand)
        t = open(sys.argv[2]).read(); open(sys.argv[2], "w").write(bake_hooks(t)); print("hooks ->", sys.argv[2])
    else:
        main(sys.argv[1], sys.argv[2])
